/**
 * Product badge enumeration
 * Badges displayed on product cards to highlight special attributes
 */
export enum ProductBadge {
  /** Product is on sale */
  SALE = 'SALE',
  /** Product is new */
  NEW = 'NEW',
  /** Product is popular/trending */
  HOT = 'HOT',
  /** Product is a best seller */
  BEST_SELLER = 'BEST_SELLER',
  /** Product is on clearance sale */
  CLEARANCE_SALE = 'CLEARANCE_SALE',
}
