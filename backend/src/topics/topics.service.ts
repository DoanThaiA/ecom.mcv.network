  /**
   * Reorder categories within a topic
   */
  async reorderCategories(
    id: string,
    dto: ReorderTopicCategoriesDto,
  ): Promise<TopicResponseDto> {
    this.logger.debug(`Reordering categories in topic ${id}`);

    const topic = await this.topicRepository.findById(id);
    if (!topic) {
      throwException({
        status: HttpStatus.NOT_FOUND,
        message: this.i18n.t('topic.notFound'),
      });
    }

    // Validate all categories in request are in the topic
    const existingCategoryIds = new Set(
      topic.categories.map((c) => c.categoryId),
    );
    const notInTopic = dto.categories.filter(
      (c) => !existingCategoryIds.has(c.categoryId),
    );

    if (notInTopic.length > 0) {
      throwException({
        status: HttpStatus.BAD_REQUEST,
        message: this.i18n.t('topic.categoryNotInTopic'),
        errors: {
          categoryIds: `Categories not in topic: ${notInTopic.map((c) => c.categoryId).join(', ')}`,
        },
      });
    }

    // Build new categories array with updated orders
    const categoriesMap = new Map(
      dto.categories.map((c) => [c.categoryId, c.order ?? 0]),
    );
    const reorderedCategories: TopicCategory[] = topic.categories.map((c) => ({
      categoryId: c.categoryId,
      order: categoriesMap.has(c.categoryId)
        ? categoriesMap.get(c.categoryId)!
        : c.order,
    }));

    const updatedTopic = await this.topicRepository.reorderCategories(
      id,
      reorderedCategories,
    );

    if (!updatedTopic) {
      throwException({
        status: HttpStatus.NOT_FOUND,
        message: this.i18n.t('topic.notFound'),
      });
    }

    return this.toResponseDto(updatedTopic);
  }

