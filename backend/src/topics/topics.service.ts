  /**
   * Update a single banner in a topic
   */
  async updateBanner(
    id: string,
    bannerId: string,
    dto: UpdateTopicBannerDto,
  ): Promise<TopicResponseDto> {
    this.logger.debug(`Updating banner ${bannerId} in topic ${id}`);

    const topic = await this.topicRepository.findById(id);
    if (!topic) {
      throwException({
        status: HttpStatus.NOT_FOUND,
        message: this.i18n.t('topic.notFound'),
      });
    }

    const bannerExists = topic.banners.some((b) => b.id === bannerId);
    if (!bannerExists) {
      throwException({
        status: HttpStatus.BAD_REQUEST,
        message: this.i18n.t('topic.bannerNotInTopic'),
      });
    }

    const updatedTopic = await this.topicRepository.updateBanner(id, bannerId, {
      mediaType: dto.mediaType,
      media: dto.media
        ? {
            mobile: dto.media.mobile,
            tablet: dto.media.tablet,
            desktop: dto.media.desktop,
          }
        : undefined,
      link: dto.link,
      order: dto.order,
    });

    if (!updatedTopic) {
      throwException({
        status: HttpStatus.NOT_FOUND,
        message: this.i18n.t('topic.notFound'),
      });
    }

    return this.toResponseDto(updatedTopic);
  }

