  /**
   * Validate products exist
   */
  private async validateProducts(productIds: string[]): Promise<void> {
    const products = await this.productRepository.findByIds(productIds);

    if (products.length !== productIds.length) {
      const foundIds = new Set(products.map((p) => p.id));
      const missingIds = productIds.filter((id) => !foundIds.has(id));
      throwException({
        status: HttpStatus.BAD_REQUEST,
        message: this.i18n.t('topic.productsNotFound'),
        errors: { productIds: `Products not found: ${missingIds.join(', ')}` },
      });
    }
  }

  /**
   * Validate categories exist
   */
  private async validateCategories(categoryIds: string[]): Promise<void> {
    const categories =
      await this.productCategoryRepository.findByIds(categoryIds);

    if (categories.length !== categoryIds.length) {
      const foundIds = new Set(categories.map((c) => c.id));
      const missingIds = categoryIds.filter((id) => !foundIds.has(id));
      throwException({
        status: HttpStatus.BAD_REQUEST,
        message: this.i18n.t('topic.categoriesNotFound'),
        errors: {
          categoryIds: `Categories not found: ${missingIds.join(', ')}`,
        },
      });
    }
  }

  /**
   * Validate slug uniqueness within a business
   */
  private async validateSlugUniqueness(
    businessId: string,
    slug: string,
    excludeId?: string,
  ): Promise<void> {
    const existingTopic = await this.topicRepository.findBySlug(
      businessId,
      slug,
    );

    if (existingTopic && existingTopic.id !== excludeId) {
      throwException({
        status: HttpStatus.CONFLICT,
        message: this.i18n.t('topic.slugExists'),
        errors: { slug: `A topic with slug "${slug}" already exists` },
      });
    }
  }

  /**
   * Convert Topic to TopicResponseDto with product and category details
   */
  private async toResponseDto(topic: Topic): Promise<TopicResponseDto> {
    // Enrich products with details
    const enrichedProducts: TopicProductResponseDto[] = await Promise.all(
      topic.products.map(async (item) => {
        const product = await this.productRepository.findById(item.productId);
        return {
          productId: item.productId,
          order: item.order,
          productName: product?.name,
          productImage: product?.images?.avatar ?? undefined,
          productPrice: product?.prices?.retail,
          productStatus: product?.status?.toString(),
        };
      }),
    );

    // Enrich categories with details
    const enrichedCategories: TopicCategoryResponseDto[] = await Promise.all(
      topic.categories.map(async (item) => {
        const category = await this.productCategoryRepository.findById(
          item.categoryId,
        );
        return {
          categoryId: item.categoryId,
          order: item.order,
          categoryName: category?.name,
          categoryImage: category?.image ?? undefined,
          categorySlug: category?.slug ?? undefined,
        };
      }),
    );

    // Sort products and categories by order
    enrichedProducts.sort((a, b) => a.order - b.order);
    enrichedCategories.sort((a, b) => a.order - b.order);

    // Map banners (no enrichment needed, data is inline)
    const enrichedBanners: TopicBannerResponseDto[] = (topic.banners || [])
      .map((b) => ({
        id: b.id,
        mediaType: b.mediaType,
        media: {
          mobile: b.media?.mobile,
          tablet: b.media?.tablet,
          desktop: b.media?.desktop,
        },
        link: b.link,
        order: b.order,
      }))
      .sort((a, b) => a.order - b.order);

    return {
      id: topic.id,
      businessId: topic.businessId,
      name: topic.name,
      localization: topic.localization
        ? { vi: topic.localization.vi, en: topic.localization.en }
        : null,
      slug: topic.slug,
      type: topic.type,
      description: topic.description,
      image: topic.image,
      order: topic.order,
      status: topic.status,
      products: enrichedProducts,
      categories: enrichedCategories,
      banners: enrichedBanners,
      productCount: topic.products.length,
      categoryCount: topic.categories.length,
      bannerCount: topic.banners.length,
      createdAt: topic.createdAt,
      updatedAt: topic.updatedAt,
    };
  }
